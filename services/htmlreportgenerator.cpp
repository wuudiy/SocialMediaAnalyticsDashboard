QString HtmlReportGenerator::buildHeaderSection(const ExportRequest& request,
                                                const QString& generatedAt) const
{
    QString html;
    QTextStream stream(&html);

    stream << "    <header class=\"hero\">\n";
    stream << "      <div class=\"hero-badge\">HTML Visual Report</div>\n";
    stream << "      <h1>Social Media Analytics Report</h1>\n";
    stream << "      <p class=\"hero-desc\">This report exports both statistical data and visual charts.</p>\n";
    stream << "      <div class=\"filter-grid\">\n";

    auto filterItem = [&](const QString& label, const QString& value) {
        stream << "        <div class=\"filter-item\">\n";
        stream << "          <span class=\"filter-label\">" << htmlEscape(label) << "</span>\n";
        stream << "          <span class=\"filter-value\">" << htmlEscape(value) << "</span>\n";
        stream << "        </div>\n";
    };

    filterItem(QStringLiteral("Generated At"), generatedAt);
    filterItem(QStringLiteral("Date Range"), dateRangeText(request.filter));
    filterItem(QStringLiteral("Platform"), displayPlatform(request.filter.platform));
    filterItem(QStringLiteral("Data Scope"), scopeText(request.filter));

    stream << "      </div>\n";
    stream << "    </header>\n";

    return html;
}

QString HtmlReportGenerator::buildSummarySection(const DashboardSummary& summary) const
{
    QString html;
    QTextStream stream(&html);

    stream << "    <section class=\"section\">\n";
    stream << "      <div class=\"section-title\">Summary Statistics</div>\n";
    stream << "      <div class=\"metric-grid\">\n";

    auto metricCard = [&](const QString& label,
                          const QString& value,
                          const QString& note) {
        stream << "        <article class=\"metric-card\">\n";
        stream << "          <div class=\"metric-label\">" << htmlEscape(label) << "</div>\n";
        stream << "          <div class=\"metric-value\">" << htmlEscape(value) << "</div>\n";
        stream << "          <div class=\"metric-note\">" << htmlEscape(note) << "</div>\n";
        stream << "        </article>\n";
    };

    metricCard(QStringLiteral("Total Posts"),
               numberText(summary.totalPosts),
               QStringLiteral("Posts in current scope"));

    metricCard(QStringLiteral("Total Interactions"),
               numberText(summary.totalInteractions),
               QStringLiteral("Likes + comments + shares"));

    metricCard(QStringLiteral("Total Views"),
               numberText(summary.totalViews),
               QStringLiteral("Views in current scope"));

    metricCard(QStringLiteral("Engagement Rate"),
               percentText(summary.averageEngagementRate),
               QStringLiteral("Interactions / views"));

    stream << "      </div>\n";
    stream << "    </section>\n";

    return html;
}

