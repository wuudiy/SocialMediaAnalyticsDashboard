GeneratedReport HtmlReportGenerator::generate(const ExportRequest& request)
{
    const ReportData data = loadReportData(request, 5);
    const QString generatedAt =
        QDateTime::currentDateTime().toString(QStringLiteral("yyyy-MM-dd HH:mm:ss"));

    QString html;
    QTextStream stream(&html);

    stream << "<!DOCTYPE html>\n";
    stream << "<html lang=\"en\">\n";
    stream << "<head>\n";
    stream << "  <meta charset=\"UTF-8\">\n";
    stream << "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n";
    stream << "  <title>Social Media Analytics Report</title>\n";
    stream << "  <style>\n";
    stream << buildStyleSheet();
    stream << "  </style>\n";
    stream << "</head>\n";
    stream << "<body>\n";
    stream << "  <main class=\"page\">\n";
    stream << buildHeaderSection(request, generatedAt);
    stream << buildSummarySection(data.summary);
    stream << buildChartsSection(data);
    stream << buildPlatformTableSection(data.platformStats);
    stream << buildTopPostsTableSection(data.topPosts);
    stream << "    <footer class=\"footer\">Generated by Social Media Analytics Dashboard</footer>\n";
    stream << "  </main>\n";
    stream << "</body>\n";
    stream << "</html>\n";

    return makeHtmlReport(html);
}

/*
 * HTML 转义。
 *
 * 用户输入的账号名、正文内容可能包含 <、>、& 等字符，
 * 如果不转义，会破坏 HTML 结构。
 */
QString HtmlEscaper::htmlEscape(const QString& value) const
{
    QString escaped = value;

    escaped.replace(QStringLiteral("&"), QStringLiteral("&amp;"));
    escaped.replace(QStringLiteral("<"), QStringLiteral("&lt;"));
    escaped.replace(QStringLiteral(">"), QStringLiteral("&gt;"));
    escaped.replace(QStringLiteral("\""), QStringLiteral("&quot;"));
    escaped.replace(QStringLiteral("'"), QStringLiteral("&#39;"));

    return escaped;
}

