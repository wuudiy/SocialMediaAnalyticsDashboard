QString HtmlReportGenerator::buildPlatformTableSection(
    const QList<PlatformStatistics>& platformStats) const
{
    QString html;
    QTextStream stream(&html);

    stream << "    <section class=\"section\">\n";
    stream << "      <div class=\"section-title\">Platform Statistics</div>\n";
    stream << "      <div class=\"table-wrap\">\n";
    stream << "        <table>\n";
    stream << "          <thead>\n";
    stream << "            <tr>\n";
    stream << "              <th>Platform</th>\n";
    stream << "              <th>Posts</th>\n";
    stream << "              <th>Likes</th>\n";
    stream << "              <th>Comments</th>\n";
    stream << "              <th>Shares</th>\n";
    stream << "              <th>Interactions</th>\n";
    stream << "              <th>Views</th>\n";
    stream << "              <th>Engagement</th>\n";
    stream << "            </tr>\n";
    stream << "          </thead>\n";
    stream << "          <tbody>\n";

    if (platformStats.isEmpty()) {
        stream << "            <tr><td class=\"empty-cell\" colspan=\"8\">No platform statistics available.</td></tr>\n";
    }

    for (const PlatformStatistics& stats : platformStats) {
        stream << "            <tr>\n";
        stream << "              <td>" << htmlEscape(stats.platform) << "</td>\n";
        stream << "              <td>" << numberText(stats.postCount) << "</td>\n";
        stream << "              <td>" << numberText(stats.totalLikes) << "</td>\n";
        stream << "              <td>" << numberText(stats.totalComments) << "</td>\n";
        stream << "              <td>" << numberText(stats.totalShares) << "</td>\n";
        stream << "              <td>" << numberText(stats.totalInteractions) << "</td>\n";
        stream << "              <td>" << numberText(stats.totalViews) << "</td>\n";
        stream << "              <td>" << htmlEscape(percentText(stats.averageEngagementRate)) << "</td>\n";
        stream << "            </tr>\n";
    }

    stream << "          </tbody>\n";
    stream << "        </table>\n";
    stream << "      </div>\n";
    stream << "    </section>\n";

    return html;
}

QString HtmlReportGenerator::buildTopPostsTableSection(const QList<Post>& topPosts) const
{
    QString html;
    QTextStream stream(&html);

    stream << "    <section class=\"section\">\n";
    stream << "      <div class=\"section-title\">Top Posts by Interactions</div>\n";
    stream << "      <div class=\"table-wrap\">\n";
    stream << "        <table>\n";
    stream << "          <thead>\n";
    stream << "            <tr>\n";
    stream << "              <th>Rank</th>\n";
    stream << "              <th>Platform</th>\n";
    stream << "              <th>Account</th>\n";
    stream << "              <th>Content</th>\n";
    stream << "              <th>Publish Date</th>\n";
    stream << "              <th>Interactions</th>\n";
    stream << "              <th>Views</th>\n";
    stream << "              <th>Engagement</th>\n";
    stream << "            </tr>\n";
    stream << "          </thead>\n";
    stream << "          <tbody>\n";

    if (topPosts.isEmpty()) {
        stream << "            <tr><td class=\"empty-cell\" colspan=\"8\">No post data available.</td></tr>\n";
    }

    int rank = 1;

    for (const Post& post : topPosts) {
        stream << "            <tr>\n";
        stream << "              <td>" << rank << "</td>\n";
        stream << "              <td>" << htmlEscape(post.platform) << "</td>\n";
        stream << "              <td>" << htmlEscape(post.accountName) << "</td>\n";
        stream << "              <td>" << htmlEscape(shortText(post.content, 120)) << "</td>\n";
        stream << "              <td>" << htmlEscape(post.publishDate.toString(QStringLiteral("yyyy-MM-dd"))) << "</td>\n";
        stream << "              <td>" << numberText(post.interactionCount()) << "</td>\n";
        stream << "              <td>" << numberText(post.views) << "</td>\n";
        stream << "              <td>" << htmlEscape(percentText(post.engagementRate())) << "</td>\n";
        stream << "            </tr>\n";

        ++rank;
    }

    stream << "          </tbody>\n";
    stream << "        </table>\n";
    stream << "      </div>\n";
    stream << "    </section>\n";

    return html;
}